import 'package:flutter/material.dart';

/// Lightweight, dependency-free localisation for English + Bengali.
///
/// Using a plain delegate (instead of generated ARB bindings) keeps the
/// project buildable without a codegen step while still supporting a runtime
/// language selector (Spec §1, §12).
class AppLocalizations {
  final Locale locale;

  const AppLocalizations(this.locale);

  static AppLocalizations of(BuildContext context) =>
      Localizations.of<AppLocalizations>(context, AppLocalizations)!;

  static const LocalizationsDelegate<AppLocalizations> delegate =
      _AppLocalizationsDelegate();

  static const List<Locale> supportedLocales = <Locale>[
    Locale('en'),
    Locale('bn'),
  ];

  static const Map<String, Map<String, String>> _data =
      <String, Map<String, String>>{
    'en': _en,
    'bn': _bn,
  };

  /// Translate a key, falling back to English then to the key itself.
  /// Placeholders use `{name}` syntax, e.g. `tr('noteCount', {'n': 3})`.
  String tr(String key, [Map<String, Object>? params]) {
    final Map<String, String> table = _data[locale.languageCode] ?? _en;
    String value = table[key] ?? _en[key] ?? key;
    if (params != null) {
      params.forEach((String k, Object v) {
        value = value.replaceAll('{$k}', '$v');
      });
    }
    return value;
  }
}

class _AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) =>
      AppLocalizations.supportedLocales
          .any((Locale l) => l.languageCode == locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) async =>
      AppLocalizations(locale);

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}

